  // ----- 예산·예산변경(관리자) / 계약(관리자·회계담당) -----
  async record_save(req, res) {
    if (!guard(req, res, ["POST"])) return;
    const { kind, id, body } = getBody(req);
    const roles = kind === "contract" ? EDITORS : ["admin"];
    if (!["contract", "budget", "budgetRevision"].includes(kind)) throw new HttpError(400, "저장할 수 없는 종류입니다.");
    const me = await requireUser(req, roles);
    let rid, rbody;
    if (kind === "contract") { const c = cleanContract(body, me.orgId); rid = c.id; rbody = c; }
    else if (kind === "budget") {
      if (!/^\d{4}$/.test(String(id))) throw new HttpError(400, "회계연도가 올바르지 않습니다.");
      rid = String(id); rbody = cleanBudget(body);
    } else {
      const rev = cleanRevision(body && body.rev);
      if (!Number.isInteger(body.fy)) throw new HttpError(400, "회계연도가 올바르지 않습니다.");
      rid = rev.id; rbody = { fy: body.fy, rev };
    }
    await tx(async q => {
      if ((kind === "budget" || kind === "budgetRevision") && (await closedYears(q, me.orgId)).has(Number(kind === "budget" ? rid : rbody.fy))) throw new HttpError(409, "마감된 회계연도의 예산은 변경할 수 없습니다.");
      await upsertRecord(q, me.orgId, kind, rid, rbody, me.id);
    });
    await audit({ orgId: me.orgId, userId: me.id, loginId: me.loginId, action: "record_save", target: `${kind}:${rid}`, ip: clientIp(req) });
    send(res, 200, { ok: true });
  },

