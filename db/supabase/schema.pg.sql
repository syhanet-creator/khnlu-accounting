-- 한수원노동조합 회계관리 시스템 - Supabase(PostgreSQL) 스키마
-- Azure SQL 스키마(db/schema.sql)와 같은 구조. 적용: node db/supabase/apply.js (관리자 접속 정보는 .env.local)
-- 아이디·조직명·결재선 이름은 대소문자를 구분하지 않는다(SQL Server 기본 동작과 같게): lower() 유일 인덱스 + 조회 시 lower() 비교.
-- 테이블은 public 이 아니라 dbo 스키마에 둔다 — Supabase 공개 API(PostgREST)에 노출되지 않고, 쿼리의 dbo. 표기도 그대로 쓴다.

CREATE SCHEMA IF NOT EXISTS dbo;

-- ===== 조직(중앙/본부/지부) =====
CREATE TABLE IF NOT EXISTS dbo.organizations (
  id             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name           varchar(100) NOT NULL,
  org_type       varchar(20)  NOT NULL CHECK (org_type IN ('central','headquarters','branch')),
  approval_steps text         NOT NULL CHECK (pg_input_is_valid(approval_steps, 'jsonb')),   -- 결재선 JSON 배열
  settings       text         NOT NULL DEFAULT '{}' CHECK (pg_input_is_valid(settings, 'jsonb')),
  current_fy     integer      NOT NULL,
  is_active      boolean      NOT NULL DEFAULT true,
  created_at     timestamptz(0) NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_organizations_name ON dbo.organizations (lower(name));

-- ===== 사용자 =====
-- role: super / admin / accountant / approver / viewer
CREATE TABLE IF NOT EXISTS dbo.users (
  id                   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  org_id               integer REFERENCES dbo.organizations(id),
  login_id             varchar(50)  NOT NULL,
  display_name         varchar(50)  NOT NULL,
  password_hash        varchar(200) NOT NULL,          -- scrypt 해시(솔트 포함). 평문은 저장하지 않는다.
  role                 varchar(20)  NOT NULL CHECK (role IN ('super','admin','accountant','approver','viewer')),
  approval_step        varchar(50),
  is_active            boolean      NOT NULL DEFAULT true,
  must_change_password boolean      NOT NULL DEFAULT true,
  failed_attempts      integer      NOT NULL DEFAULT 0,
  locked_until         timestamptz(0),
  last_login_at        timestamptz(0),
  created_at           timestamptz(0) NOT NULL DEFAULT now(),
  created_by           integer,
  signature_id         integer,
  CONSTRAINT ck_users_org CHECK ((role = 'super' AND org_id IS NULL) OR (role <> 'super' AND org_id IS NOT NULL)),
  CONSTRAINT ck_users_step CHECK (role = 'approver' OR approval_step IS NULL)
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_users_login ON dbo.users (lower(login_id));

-- ===== 로그인 세션 (토큰 원문은 저장하지 않고 SHA-256 해시만) =====
CREATE TABLE IF NOT EXISTS dbo.sessions (
  token_hash   varchar(64)  NOT NULL PRIMARY KEY,
  user_id      integer      NOT NULL REFERENCES dbo.users(id),
  created_at   timestamptz(0) NOT NULL DEFAULT now(),
  expires_at   timestamptz(0) NOT NULL,
  last_seen_at timestamptz(0) NOT NULL DEFAULT now(),
  ip           varchar(45),
  user_agent   varchar(200)
);
CREATE INDEX IF NOT EXISTS ix_sessions_user ON dbo.sessions(user_id);

-- ===== 전표(회계결의서) =====
CREATE TABLE IF NOT EXISTS dbo.vouchers (
  org_id       integer      NOT NULL REFERENCES dbo.organizations(id),
  id           varchar(40)  NOT NULL,
  doc_no       varchar(40)  NOT NULL,
  voucher_date date         NOT NULL,
  title        varchar(200) NOT NULL DEFAULT '',
  voucher_type varchar(20)  NOT NULL,
  status       varchar(20)  NOT NULL CHECK (status IN ('draft','pending','approved','rejected')),
  body         text         NOT NULL CHECK (pg_input_is_valid(body, 'jsonb')),
  version      integer      NOT NULL DEFAULT 1,
  created_by   integer      NOT NULL REFERENCES dbo.users(id),
  created_at   timestamptz(0) NOT NULL DEFAULT now(),
  updated_by   integer      NOT NULL REFERENCES dbo.users(id),
  updated_at   timestamptz(0) NOT NULL DEFAULT now(),
  CONSTRAINT pk_vouchers PRIMARY KEY (org_id, id),
  CONSTRAINT ux_vouchers_docno UNIQUE (org_id, doc_no)
);
CREATE INDEX IF NOT EXISTS ix_vouchers_date ON dbo.vouchers(org_id, voucher_date);
CREATE INDEX IF NOT EXISTS ix_vouchers_status ON dbo.vouchers(org_id, status);

-- 결재 이력
CREATE TABLE IF NOT EXISTS dbo.voucher_approvals (
  org_id             integer      NOT NULL,
  voucher_id         varchar(40)  NOT NULL,
  step_name          varchar(50)  NOT NULL,
  approved_by        integer      NOT NULL REFERENCES dbo.users(id),
  approved_at        timestamptz(0) NOT NULL DEFAULT now(),
  acting_for_user_id integer REFERENCES dbo.users(id),
  signature_id       integer,
  CONSTRAINT pk_voucher_approvals PRIMARY KEY (org_id, voucher_id, step_name),
  CONSTRAINT fk_voucher_approvals_voucher FOREIGN KEY (org_id, voucher_id)
    REFERENCES dbo.vouchers(org_id, id) ON DELETE CASCADE
);

-- 전표번호 채번(조직 + 연월별 순번)
CREATE TABLE IF NOT EXISTS dbo.doc_counters (
  org_id  integer  NOT NULL REFERENCES dbo.organizations(id),
  ym      varchar(6) NOT NULL,
  last_no integer  NOT NULL DEFAULT 0,
  CONSTRAINT pk_doc_counters PRIMARY KEY (org_id, ym)
);

-- ===== 그 외 업무 데이터(예산·예산변경·비품·계약·연도마감) =====
CREATE TABLE IF NOT EXISTS dbo.records (
  org_id     integer      NOT NULL REFERENCES dbo.organizations(id),
  kind       varchar(20)  NOT NULL CHECK (kind IN ('budget','budgetRevision','asset','contract','yearClosing')),
  id         varchar(40)  NOT NULL,
  body       text         NOT NULL CHECK (pg_input_is_valid(body, 'jsonb')),
  version    integer      NOT NULL DEFAULT 1,
  updated_by integer      NOT NULL REFERENCES dbo.users(id),
  updated_at timestamptz(0) NOT NULL DEFAULT now(),
  CONSTRAINT pk_records PRIMARY KEY (org_id, kind, id)
);

-- ===== 감사 로그 (추가·조회만 가능: 앱 계정에는 수정/삭제 권한을 주지 않는다) =====
CREATE TABLE IF NOT EXISTS dbo.audit_log (
  id       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  at       timestamptz(0) NOT NULL DEFAULT now(),
  org_id   integer,
  user_id  integer,
  login_id varchar(50),
  action   varchar(40)  NOT NULL,
  target   varchar(100),
  detail   text,
  ip       varchar(45)
);
CREATE INDEX IF NOT EXISTS ix_audit_org_at ON dbo.audit_log(org_id, at);

-- ===== 결재선 선택 · 대결 =====
CREATE TABLE IF NOT EXISTS dbo.approval_lines (
  id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  org_id     integer      NOT NULL REFERENCES dbo.organizations(id),
  name       varchar(40)  NOT NULL,
  steps      text         NOT NULL CHECK (pg_input_is_valid(steps, 'jsonb')),
  is_active  boolean      NOT NULL DEFAULT true,
  created_by integer,
  created_at timestamptz(0) NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_approval_lines_name ON dbo.approval_lines (org_id, lower(name));

CREATE TABLE IF NOT EXISTS dbo.approval_delegations (
  id               integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  org_id           integer      NOT NULL REFERENCES dbo.organizations(id),
  step_name        varchar(50)  NOT NULL,
  absent_user_id   integer      NOT NULL REFERENCES dbo.users(id),
  delegate_user_id integer      NOT NULL REFERENCES dbo.users(id),
  from_date        date         NOT NULL,
  to_date          date         NOT NULL,
  note             varchar(100),
  is_active        boolean      NOT NULL DEFAULT true,
  created_by       integer      NOT NULL,
  created_at       timestamptz(0) NOT NULL DEFAULT now(),
  CONSTRAINT ck_delegation_dates CHECK (to_date >= from_date),
  CONSTRAINT ck_delegation_diff CHECK (absent_user_id <> delegate_user_id)
);
CREATE INDEX IF NOT EXISTS ix_delegations_lookup ON dbo.approval_delegations(org_id, step_name, delegate_user_id, is_active);

-- ===== 결재자 서명 =====
CREATE TABLE IF NOT EXISTS dbo.user_signatures (
  id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  org_id     integer      NOT NULL REFERENCES dbo.organizations(id),
  user_id    integer      NOT NULL REFERENCES dbo.users(id),
  mime       varchar(20)  NOT NULL,
  data       bytea        NOT NULL,
  width      integer      NOT NULL,
  height     integer      NOT NULL,
  created_at timestamptz(0) NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_user_signatures_user ON dbo.user_signatures(org_id, user_id);

-- ===== 접근 통제 =====
-- 모든 테이블에 행 수준 보안(RLS)을 켠다. Supabase 의 anon/authenticated 역할은 정책이 없어 아무것도 못 한다.
-- 앱 전용 역할(app_user)만 정책으로 허용하며, 감사 로그는 추가·조회만 허용한다.
DO $$
DECLARE t text;
BEGIN
  FOREACH t IN ARRAY ARRAY['organizations','users','sessions','vouchers','voucher_approvals','doc_counters','records','audit_log','approval_lines','approval_delegations','user_signatures']
  LOOP
    EXECUTE format('ALTER TABLE dbo.%I ENABLE ROW LEVEL SECURITY', t);
  END LOOP;
END $$;
